#!/usr/bin/env bash
# Dockyard installer.
#
# Takes a fresh Linux host to a running panel: Docker Engine with the Compose plugin, git (the
# updater pulls the checkout, so the deployed directory has to be a clone), curl and openssl for the
# generated secrets, then the panel and its Postgres, then the host updater. It finishes by asking
# the panel whether it is up, so a green summary means the API answered, not that a command exited 0.
#
#   curl -fsSL https://raw.githubusercontent.com/dockyardapp/dockyard/main/install.sh | sudo bash
#
# or, from a checkout you already have:
#
#   sudo ./install.sh
#
# Re-running is safe. An existing checkout is reused, an existing .env is never rewritten, and the
# image is rebuilt from whatever the checkout holds.
#
# Flags:
#   --dir PATH          where to install (default: this checkout, else /opt/dockyard)
#   --port N            host port to publish the panel on (default 8000)
#   --bind ADDR         address to publish on (default 0.0.0.0; 127.0.0.1 keeps it on the host).
#                       With --proxy this is the address nginx publishes on, and the panel moves to
#                       127.0.0.1 either way, because nginx is meant to be the only public door.
#   --public-url URL    the URL the panel will be reached at, used for the links it shows
#   --email ADDR        admin account email (default admin@dockyard.local)
#   --password PASS     admin password (generated and shown once if you do not pass one)
#   --no-admin          leave the admin account unset and register it in the UI instead
#   --repo URL          repository to clone (default the public Dockyard repository)
#   --branch NAME       branch to install (default main)
#   --no-updater        skip the host updater; the Install update button stays disabled
#   --no-firewall       never touch the firewall, only report what it would need
#   --proxy             put nginx in front of the panel, so nginx is the only public door
#   --no-proxy          no nginx; the panel itself is the door (default)
#   --cert MODE         self-signed | letsencrypt | none (default: none, or self-signed with --proxy)
#   --domain NAME       the name or IP the panel is reached at, used for nginx and the certificate
#   --http-port N       nginx HTTP port (default 80)
#   --https-port N      nginx HTTPS port (default 443)
#   --tui               force the interactive setup even when it would not normally run
#   --no-tui            never run it; take the flags and the defaults as given
#   --dry-run           print what would happen and change nothing
#   -h, --help          this
#
# Run with no flags on a terminal and it walks you through the choices it cannot make for you: how
# the panel should be reached, whether nginx terminates TLS, what certificate to use, and which
# address to listen on. Passing any of --proxy, --cert, --domain, --bind or --email is taken as
# having answered, and the questions are skipped. Piped into bash with no terminal it stays
# non-interactive and uses the defaults, so `curl | bash` still installs unattended.
#
# Why nginx is off by default: it needs ports 80 and 443, and that is a decision about the host, not
# about the app. When it is on, the panel is republished on 127.0.0.1 so nginx is the only public
# door. That matters more than it sounds: the panel mounts the Docker socket, so its port is a
# root-equivalent door, and until now the installer published it on every interface with a plain
# HTTP session cookie.
#
# Why an admin password is generated by default: the panel mounts the Docker socket, so anyone who
# can sign in has root-equivalent control of the host. The user table is empty until an account
# exists, and while it is empty the bootstrap route is open, so an install published on a public
# address with no password set is a race that whoever finds the port first wins. Generating one
# closes that window. Pass --no-admin to take the race deliberately.
set -Eeuo pipefail

DEFAULT_REPO_URL="https://github.com/dockyardapp/dockyard.git"
DEFAULT_EMAIL="admin@dockyard.local"

INSTALL_DIR=""
PANEL_PORT="8000"
PANEL_BIND="0.0.0.0"
PUBLIC_URL=""
ADMIN_EMAIL="$DEFAULT_EMAIL"
ADMIN_PASSWORD=""
ADMIN_GENERATED="no"
REPO_URL="$DEFAULT_REPO_URL"
BRANCH="main"
INSTALL_UPDATER="yes"
SET_ADMIN="yes"
TOUCH_FIREWALL="yes"
DRY_RUN="no"

# --- the reverse proxy and the interactive setup ---
# PROXY_ENABLE is off by default because nginx wants ports 80 and 443, which is a decision about the
# host rather than about the app. CERT_MODE=none with PROXY_ENABLE=yes is a real combination: it is
# the "something else already terminates TLS" case, and also the plain-HTTP case behind a tunnel.
PROXY_ENABLE="no"
PROXY_BIND="0.0.0.0"
PROXY_HTTP_PORT="80"
PROXY_HTTPS_PORT="443"
CERT_MODE="none"
CERT_MODE_SET="no"
DOMAIN=""
TUI="auto"
# Set when a flag that answers one of the TUI's questions is seen, so the questions are not asked
# again. --dry-run counts: a dry run should not stop for input.
DECIDED="no"
# Narrower than DECIDED: whether the proxy itself was chosen. Only then are the proxy settings
# applied to an .env that already exists, so a run that never mentions nginx cannot disturb one.
PROXY_DECIDED="no"
# Whether --bind was given. With the proxy on, that address belongs to nginx rather than the panel,
# so it has to be told apart from the default.
BIND_SET="no"

COMPOSE=()

say()  { printf '  %s\n' "$*"; }
step() { printf '\n%s\n' "$*"; }
# Warnings go to stdout with the rest of the report, not to stderr. This script's output is a
# document a person reads top to bottom, and splitting it across two streams means `./install.sh |
# tee install.log` shows every warning before the step it belongs to.
warn() { printf '  ! %s\n' "$*"; }
die()  { printf '\n  x %s\n\n' "$*" >&2; exit 1; }

# Mutating commands go through these, so --dry-run has exactly one meaning: nothing changes.
run() {
  if [ "$DRY_RUN" = "yes" ]; then
    printf '  [dry-run] %s\n' "$*"
    return 0
  fi
  "$@"
}
run_sh() {
  if [ "$DRY_RUN" = "yes" ]; then
    printf '  [dry-run] sh -c %s\n' "$1"
    return 0
  fi
  sh -c "$1"
}

# For steps whose output is loud and uninteresting: a package manager unpacking a hundred
# dependencies buries the report this script exists to print. Capture it and surface it only when the
# step fails, so a failure is still fully explained.
run_quiet() {
  if [ "$DRY_RUN" = "yes" ]; then
    printf '  [dry-run] %s\n' "$*"
    return 0
  fi
  local log
  log="$(mktemp)"
  if "$@" >"$log" 2>&1; then
    rm -f "$log"
    return 0
  fi
  printf '  step failed: %s\n' "$*"
  sed 's/^/    /' "$log"
  rm -f "$log"
  return 1
}
run_quiet_sh() {
  if [ "$DRY_RUN" = "yes" ]; then
    printf '  [dry-run] sh -c %s\n' "$1"
    return 0
  fi
  local log
  log="$(mktemp)"
  if sh -c "$1" >"$log" 2>&1; then
    rm -f "$log"
    return 0
  fi
  printf '  step failed: sh -c %s\n' "$1"
  sed 's/^/    /' "$log"
  rm -f "$log"
  return 1
}

# ---------------------------------------------------------------------------- helpers
#
# Defined here, above every use. Bash resolves a function at call time, so a helper defined further
# down the file is a "command not found" at whatever line calls it first.

# The last assignment of a key wins, so an operator's appended override is the one that counts.
env_value() {
  sed -n "s/^$1=//p" "$ENV_FILE" 2>/dev/null | tail -1 | sed -e 's/^"//' -e 's/"$//' || true
}

# Rewrites one key in an existing .env, in place, or appends it when it is absent. Used only for the
# proxy settings: they are not secrets, they describe how the host should be reached rather than what
# the database was created with, and the operator has just asked for them. The generated secrets are
# never touched by this, which is the property that makes keeping an existing .env safe.
set_env_key() {
  local key="$1" value="$2"
  if grep -qE "^$key=" "$ENV_FILE"; then
    run sed -i "s|^$key=.*|$key=$value|" "$ENV_FILE"
  else
    run_sh "printf '%s=%s\n' '$key' '$value' >> '$ENV_FILE'"
  fi
}

# Every ${VAR:?...} in the compose file is something the deployment refuses to start without. Read
# the requirement off the compose file instead of repeating it here, so the two cannot drift.
required_keys() {
  grep -oE '\$\{[A-Z_]+:\?' "$INSTALL_DIR/docker-compose.yml" 2>/dev/null \
    | sed -E 's/\$\{([A-Z_]+):\?/\1/' | sort -u || true
}

# The docker group id, without assuming getent is installed.
docker_group_id() {
  if command -v getent >/dev/null 2>&1; then
    getent group docker 2>/dev/null | cut -d: -f3 || true
  else
    grep '^docker:' /etc/group 2>/dev/null | cut -d: -f3 || true
  fi
}

# A best-effort address to put in PUBLIC_URL, which only decides the links the UI shows. `ip` lives
# in iproute2 and is absent from minimal images, so nothing here may be required for the install to
# continue: the fallback is localhost, and --public-url overrides it.
detect_host_ip() {
  local found=""
  if command -v ip >/dev/null 2>&1; then
    found="$(ip -4 route get 1.1.1.1 2>/dev/null | awk '{for(i=1;i<=NF;i++) if($i=="src"){print $(i+1); exit}}' || true)"
  fi
  if [ -z "$found" ] && command -v hostname >/dev/null 2>&1; then
    found="$(hostname -I 2>/dev/null | awk '{print $1}' || true)"
  fi
  [ -n "$found" ] || found="localhost"
  printf '%s' "$found"
}

usage() {
  # The header comment is the help text: print it and stop at the first line that is not a comment,
  # so the script body below can never leak into --help.
  awk 'NR > 1 && /^#/ { sub(/^# ?/, ""); print; next } NR > 1 { exit }' "${BASH_SOURCE[0]}"
  exit 0
}

# ---------------------------------------------------------------------------- arguments

# Before parsing, work out whether this script is sitting inside a checkout. If it is, that is the
# directory to install, because it already has an origin remote for the updater to pull.
SCRIPT_PATH="${BASH_SOURCE[0]:-}"
CHECKOUT_DIR=""
if [ -n "$SCRIPT_PATH" ] && [ -f "$SCRIPT_PATH" ]; then
  HERE="$(cd "$(dirname "$SCRIPT_PATH")" && pwd)"
  if [ -f "$HERE/docker-compose.yml" ] && [ -f "$HERE/server/src/index.ts" ]; then
    CHECKOUT_DIR="$HERE"
  fi
fi
INSTALL_DIR="${CHECKOUT_DIR:-/opt/dockyard}"

while [ $# -gt 0 ]; do
  case "$1" in
    --dir)        [ $# -ge 2 ] || die "--dir needs a path";        INSTALL_DIR="$2"; shift 2 ;;
    --port)       [ $# -ge 2 ] || die "--port needs a number";     PANEL_PORT="$2";  shift 2 ;;
    --bind)       [ $# -ge 2 ] || die "--bind needs an address";   PANEL_BIND="$2"; BIND_SET="yes"; DECIDED="yes"; shift 2 ;;
    --public-url) [ $# -ge 2 ] || die "--public-url needs a URL";  PUBLIC_URL="$2";   shift 2 ;;
    --email)      [ $# -ge 2 ] || die "--email needs an address";  ADMIN_EMAIL="$2"; shift 2 ;;
    --password)   [ $# -ge 2 ] || die "--password needs a value";  ADMIN_PASSWORD="$2"; shift 2 ;;
    --repo)       [ $# -ge 2 ] || die "--repo needs a URL";        REPO_URL="$2";    shift 2 ;;
    --branch)     [ $# -ge 2 ] || die "--branch needs a name";     BRANCH="$2";      shift 2 ;;
    --no-admin)   SET_ADMIN="no"; shift ;;
    --no-updater) INSTALL_UPDATER="no"; shift ;;
    --no-firewall) TOUCH_FIREWALL="no"; shift ;;
    --proxy)      PROXY_ENABLE="yes"; DECIDED="yes"; PROXY_DECIDED="yes"; shift ;;
    --no-proxy)   PROXY_ENABLE="no";  DECIDED="yes"; PROXY_DECIDED="yes"; shift ;;
    --cert)       [ $# -ge 2 ] || die "--cert needs a mode";  CERT_MODE="$2"; CERT_MODE_SET="yes"; DECIDED="yes"; shift 2 ;;
    --domain)     [ $# -ge 2 ] || die "--domain needs a name"; DOMAIN="$2";   DECIDED="yes"; shift 2 ;;
    --http-port)  [ $# -ge 2 ] || die "--http-port needs a number";  PROXY_HTTP_PORT="$2";  DECIDED="yes"; shift 2 ;;
    --https-port) [ $# -ge 2 ] || die "--https-port needs a number"; PROXY_HTTPS_PORT="$2"; DECIDED="yes"; shift 2 ;;
    --tui)        TUI="yes"; shift ;;
    --no-tui)     TUI="no"; shift ;;
    --dry-run)    DRY_RUN="yes"; DECIDED="yes"; shift ;;
    -h|--help)    usage ;;
    *) die "unknown flag: $1 (try --help)" ;;
  esac
done

case "$PANEL_PORT" in
  ''|*[!0-9]*) die "--port must be a number, got '$PANEL_PORT'" ;;
esac

case "$PROXY_HTTP_PORT" in
  ''|*[!0-9]*) die "--http-port must be a number, got '$PROXY_HTTP_PORT'" ;;
esac
case "$PROXY_HTTPS_PORT" in
  ''|*[!0-9]*) die "--https-port must be a number, got '$PROXY_HTTPS_PORT'" ;;
esac

case "$CERT_MODE" in
  self-signed|letsencrypt|none) ;;
  *) die "--cert must be self-signed, letsencrypt or none, got '$CERT_MODE'" ;;
esac

# --proxy on its own means "nginx with TLS", because that is the useful reading and the one a person
# typing it by hand means. Plain HTTP behind nginx is still reachable with an explicit --cert none.
if [ "$PROXY_ENABLE" = "yes" ] && [ "$CERT_MODE_SET" = "no" ] && [ "$DECIDED" = "yes" ]; then
  CERT_MODE="self-signed"
fi

# A certificate needs a name to be issued for. An IP is a legitimate name here (the self-signed path
# puts it in the SAN, and a browser will then match it), so this is only about having *something*.
if [ "$CERT_MODE" != "none" ] && [ -z "$DOMAIN" ] && [ "$DECIDED" = "yes" ]; then
  die "--cert $CERT_MODE needs --domain NAME (a domain, or this host's IP)."
fi

# ---------------------------------------------------------------------------- the interactive setup
#
# Keys are read from /dev/tty, never from stdin, and that is not a detail: under
# `curl -fsSL ... | bash` the script itself is on stdin, so a plain `read` would consume the rest of
# the script instead of a keystroke. Drawing goes to /dev/tty too, so the menus stay out of
# `./install.sh | tee install.log` while the report afterwards still goes to stdout, where a reader
# expects it.
#
# Plain ANSI, with no dependency on whiptail or dialog: this runs on a host that may have no working
# package manager, which is the situation the installer exists for. It uses the alternate screen, so
# it leaves no scrollback behind, and an EXIT trap restores the terminal even if it is interrupted.

TUI_ACTIVE="no"
TUI_CHOICE=0
TUI_TEXT=""
TUI_SECRET="no"
TUI_BOLD=""; TUI_DIM=""; TUI_REV=""; TUI_OFF=""

tui_colours() {
  [ -n "${NO_COLOR:-}" ] && return 0
  TUI_BOLD=$'\033[1m'; TUI_DIM=$'\033[2m'; TUI_REV=$'\033[7m'; TUI_OFF=$'\033[0m'
}

# fd 3 is the terminal for the whole run. No controlling terminal means no TUI, and that is a
# fallback rather than an error: `curl | bash` from cron has nobody to answer a menu.
#
# The probe is a subshell so that a failure is reported to nobody. `exec 3<>/dev/tty 2>/dev/null`
# does not suppress bash's own message, because the shell reports the failed redirection before it
# applies the later ones, and that message would land in the operator's terminal or a captured log.
tui_open() {
  if ! (exec 3<>/dev/tty) 2>/dev/null; then
    return 1
  fi
  exec 3<>/dev/tty
  # The terminal has to be handed back even if the operator interrupts the installer mid-menu, or the
  # shell they land back in is left inside the alternate screen with the cursor hidden.
  trap 'tui_on_exit' EXIT INT TERM
  TUI_ACTIVE="yes"
  return 0
}

tui_close() {
  [ "$TUI_ACTIVE" = "yes" ] || return 0
  printf '\033[?25h\033[?1049l' >&3 2>/dev/null || true
  TUI_ACTIVE="no"
}

# A terminal left inside the alternate screen by a failure is the one thing a TUI must never do.
tui_on_exit() { tui_close; }

tui_begin() {
  printf '\033[?1049h\033[?25l' >&3
}

# One keystroke, as a word: UP DOWN LEFT RIGHT ENTER ESC BACKSPACE, or the character itself.
tui_key() {
  local k a b
  IFS= read -rsn1 -u 3 k || return 1
  case "$k" in
    '') printf 'ENTER' ;;
    $'\x7f'|$'\x08') printf 'BACKSPACE' ;;
    $'\x1b')
      IFS= read -rsn1 -t 0.05 -u 3 a 2>/dev/null || { printf 'ESC'; return 0; }
      IFS= read -rsn1 -t 0.05 -u 3 b 2>/dev/null || b=""
      case "$a$b" in
        '[A') printf 'UP' ;;
        '[B') printf 'DOWN' ;;
        '[C') printf 'RIGHT' ;;
        '[D') printf 'LEFT' ;;
        *) printf 'ESC' ;;
      esac
      ;;
    *) printf '%s' "$k" ;;
  esac
  return 0
}

# Reading can fail (a terminal that has gone away), and an unguarded `key="$(tui_key)"` would then
# trip `set -e` on the assignment itself. ESC is the honest answer: the caller unwinds.
tui_ask_key() {
  local k
  k="$(tui_key)" || k='ESC'
  printf '%s' "$k"
}

tui_screen() {
  printf '\033[2J\033[H' >&3
  printf '\n' >&3
}

tui_title() {
  printf '  %s%s%s\n\n' "$TUI_BOLD" "$1" "$TUI_OFF" >&3
}

tui_text() {
  printf '  %s%s%s\n' "$TUI_DIM" "$1" "$TUI_OFF" >&3
}

tui_footer() {
  printf '\n  %s%s%s\n' "$TUI_DIM" "$1" "$TUI_OFF" >&3
}

# An informational screen. Returns non-zero if the operator backs out.
tui_message() {
  local title="$1" body="$2" key
  while :; do
    tui_screen
    tui_title "$title"
    printf '%s\n' "$body" | while IFS= read -r line; do
      printf '  %s\n' "$line" >&3
    done
    tui_footer "enter continues, q quits"
    key="$(tui_ask_key)"
    case "$key" in
      ENTER) return 0 ;;
      q|Q|ESC) return 1 ;;
    esac
  done
}

# tui_menu TITLE PROMPT DEFAULT_INDEX "label|description"...
# Sets TUI_CHOICE to the chosen index. Non-zero if the operator backs out.
tui_menu() {
  local title="$1" prompt="$2" def="$3"; shift 3
  local -a labels=() descs=()
  local item n sel i key
  for item in "$@"; do
    labels+=("${item%%|*}")
    descs+=("${item#*|}")
  done
  n=${#labels[@]}
  sel="$def"

  while :; do
    tui_screen
    tui_title "$title"
    [ -n "$prompt" ] && printf '  %s\n\n' "$prompt" >&3
    for ((i = 0; i < n; i++)); do
      if [ "$i" -eq "$sel" ]; then
        printf '  %s> %s%s\n' "$TUI_REV" "${labels[$i]}" "$TUI_OFF" >&3
      else
        printf '    %s\n' "${labels[$i]}" >&3
      fi
      [ -n "${descs[$i]}" ] && tui_text "      ${descs[$i]}"
      printf '\n' >&3
    done
    tui_footer "up/down or j/k move, enter selects, q goes back"

    key="$(tui_ask_key)"
    case "$key" in
      UP|k)      sel=$(((sel - 1 + n) % n)) ;;
      DOWN|j)    sel=$(((sel + 1) % n)) ;;
      ENTER|' ') TUI_CHOICE="$sel"; return 0 ;;
      q|Q|ESC)   return 1 ;;
      [1-9])     [ "$key" -le "$n" ] && { TUI_CHOICE=$((key - 1)); return 0; } ;;
    esac
  done
}

# A password typed at this prompt is echoed as asterisks. TUI_SECRET is set by the caller and cleared
# again, so the same widget serves a domain name and a password.
tui_echo() {
  if [ "$TUI_SECRET" = "yes" ]; then
    printf '%s' "$1" | sed 's/./*/g'
  else
    printf '%s' "$1"
  fi
}

# tui_input TITLE PROMPT DEFAULT -> TUI_TEXT. Non-zero if the operator backs out.
tui_input() {
  local title="$1" prompt="$2" def="${3:-}"
  local buf="$def" key
  while :; do
    tui_screen
    tui_title "$title"
    [ -n "$prompt" ] && printf '  %s\n\n' "$prompt" >&3
    printf '  %s>%s %s\n' "$TUI_BOLD" "$TUI_OFF" "$(tui_echo "$buf")" >&3
    tui_footer "enter accepts, backspace deletes, ctrl-c quits"

    key="$(tui_ask_key)"
    case "$key" in
      ENTER)     TUI_TEXT="$buf"; return 0 ;;
      BACKSPACE) buf="${buf%?}" ;;
      UP|DOWN|LEFT|RIGHT|ESC|TAB) : ;;
      ?)         buf="$buf$key" ;;
    esac
  done
}

# ---------------------------------------------------------------------------- the questions

# The last screen before anything is written.
tui_review() {
  local reach cert_line bind_line account
  if [ "$PROXY_ENABLE" = "yes" ]; then
    if [ "$CERT_MODE" = "none" ]; then
      cert_line="no TLS (nginx serves plain HTTP on $PROXY_HTTP_PORT)"
    else
      cert_line="$CERT_MODE certificate for $DOMAIN, on port $PROXY_HTTPS_PORT"
    fi
    reach="nginx on ${PUBLIC_BIND:-0.0.0.0}, forwarding to the panel"
  else
    cert_line="no TLS"
    reach="the panel itself on ${PUBLIC_BIND:-0.0.0.0}:$PANEL_PORT"
  fi
  bind_line="${PUBLIC_BIND:-0.0.0.0}"

  if [ -n "$ADMIN_PASSWORD" ]; then
    account="$ADMIN_EMAIL (with the password you typed)"
  else
    account="$ADMIN_EMAIL (password generated)"
  fi

  tui_message "Ready to install" \
"Here is what will happen.

  reached at     $reach
  listening on   $bind_line
  certificate    $cert_line
  install to     $INSTALL_DIR
  first account  $account

  $([ "$PROXY_ENABLE" = "yes" ] && printf 'The panel moves to 127.0.0.1:%s, so nginx is the only public door.' "$PANEL_PORT" || printf 'The panel is published directly, and it controls Docker.')

Enter installs. q goes back to the questions." 
}

# Walks the choices the installer cannot make for the operator. Sets PROXY_ENABLE, CERT_MODE,
# DOMAIN, the bind addresses, the proxy ports and the first account. The caller owns the terminal:
# fd 3 is already open by the time this runs.
tui_configure() {
  tui_colours
  tui_begin

  tui_message "Dockyard installer" \
"This will install Docker and the Compose plugin, build the panel, start it with
Postgres, and optionally put nginx in front of it with a certificate.

It needs root, and it takes a few minutes on a small host.

Nothing is written until the last screen, so you can back out at any point." || return 1

  # --- how the panel is reached
  tui_menu "How should the panel be reached?" \
"nginx is the only public door, and the panel moves to 127.0.0.1 behind it." 0 \
    "Behind nginx, with TLS|Recommended on a host with a public address. nginx terminates TLS, and the panel stops being published on every interface." \
    "Behind nginx, plain HTTP|For a host where something else already terminates TLS, or that is only reached over a tunnel." \
    "Directly, no proxy|The panel is the door. Plain HTTP, on whatever address you pick next." || return 1
  case "$TUI_CHOICE" in
    0) PROXY_ENABLE="yes"; CERT_MODE="self-signed" ;;
    1) PROXY_ENABLE="yes"; CERT_MODE="none" ;;
    2) PROXY_ENABLE="no";  CERT_MODE="none" ;;
  esac
  PROXY_DECIDED="yes"

  # --- the certificate
  if [ "$CERT_MODE" != "none" ]; then
    tui_menu "What certificate?" \
"A self-signed one works immediately. Let's Encrypt needs a public domain." 0 \
      "Self-signed|Generated now, for the name you give next. Browsers warn until you accept it, which is fine for a panel only you reach." \
      "Let's Encrypt|A certificate every browser trusts. It needs a domain that already points here and port 80 reachable from the internet." || return 1
    case "$TUI_CHOICE" in
      0) CERT_MODE="self-signed" ;;
      1) CERT_MODE="letsencrypt" ;;
    esac

    # --- the name
    if [ "$CERT_MODE" = "letsencrypt" ]; then
      tui_input "The domain" \
"This name must already resolve to this host, and port 80 must be reachable from
the internet, or the certificate authority cannot confirm you own it." "" || return 1
      DOMAIN="$TUI_TEXT"
      if [ -z "$DOMAIN" ]; then
        tui_message "A domain is required" \
"Let's Encrypt will not issue a certificate without a name it can reach this host
on. Go back and either give one, or choose a self-signed certificate instead." || return 1
        return 1
      fi
    else
      tui_input "The name on the certificate" \
"The address you will type to reach the panel. A domain or this host's IP both
work: either goes into the certificate, and either will match." "$(detect_host_ip)" || return 1
      DOMAIN="$TUI_TEXT"
      if [ -z "$DOMAIN" ]; then
        tui_message "A name is required" \
"A certificate is issued for a name. Give the address you will reach the panel on." || return 1
        return 1
      fi
    fi
  fi

  # --- which address the public door listens on
  tui_menu "Which address should it listen on?" \
"This is the address the panel (or nginx, when it is in front) is published on." 0 \
    "All interfaces (0.0.0.0)|Reachable from anywhere this host is reachable from." \
    "Loopback only (127.0.0.1)|Only from this machine. Reach it through a tunnel, an SSH forward, or your own proxy." \
    "A specific address|Type one, for example 10.0.0.5 or a Tailscale address." || return 1
  case "$TUI_CHOICE" in
    0) PUBLIC_BIND="0.0.0.0" ;;
    1) PUBLIC_BIND="127.0.0.1" ;;
    2)
      tui_input "Which address?" "The address to publish on." "$(detect_host_ip)" || return 1
      PUBLIC_BIND="$TUI_TEXT"
      if [ -z "$PUBLIC_BIND" ]; then
        tui_message "An address is required" "Go back and pick one of the first two, or type an address." || return 1
        return 1
      fi
      ;;
  esac

  # --- the ports nginx listens on
  if [ "$PROXY_ENABLE" = "yes" ]; then
    tui_menu "Which ports should nginx use?" \
"These are the host's ports. The panel itself stays on $PANEL_PORT." 0 \
      "The standard ones (80 and 443)|What a browser assumes, and what Let's Encrypt needs." \
      "Different ports|For a host where 80 or 443 is already taken." || return 1
    if [ "$TUI_CHOICE" -eq 1 ]; then
      tui_input "HTTP port" "Plain HTTP. Keep it if you want the redirect to https to work." "8080" || return 1
      PROXY_HTTP_PORT="$TUI_TEXT"
      case "$PROXY_HTTP_PORT" in ''|*[!0-9]*) PROXY_HTTP_PORT="8080" ;; esac
      tui_input "HTTPS port" "The TLS port." "8443" || return 1
      PROXY_HTTPS_PORT="$TUI_TEXT"
      case "$PROXY_HTTPS_PORT" in ''|*[!0-9]*) PROXY_HTTPS_PORT="8443" ;; esac
    fi
  fi

  # --- the first account
  tui_input "The first account" \
"The panel mounts the Docker socket, so whoever can sign in controls this host.
Leave the password blank and one will be generated and shown once at the end." "$ADMIN_EMAIL" || return 1
  [ -n "$TUI_TEXT" ] && ADMIN_EMAIL="$TUI_TEXT"

  TUI_SECRET="yes"
  tui_input "Password for $ADMIN_EMAIL" \
"Leave this blank to have one generated. It is shown once at the end of the
install and written to the config file, which is mode 0600." "" || return 1
  TUI_SECRET="no"
  if [ -n "$TUI_TEXT" ]; then
    ADMIN_PASSWORD="$TUI_TEXT"
  else
    ADMIN_PASSWORD=""
  fi

  # --- the summary
  tui_review || return 1

  tui_close
  return 0
}

# The panel is reached over TLS or it is not, and that single fact decides two settings that must
# agree with each other.
derive_settings() {
  TLS_ON="no"
  if [ "$PROXY_ENABLE" = "yes" ] && [ "$CERT_MODE" != "none" ]; then
    TLS_ON="yes"
  fi

  # The address the operator chose belongs to the public door: nginx when there is one, the panel
  # otherwise. With the proxy on that makes --bind name where nginx publishes, and the panel's own
  # address stops being a choice, because it has to be loopback. Two reasons, both real: the panel
  # port is a Docker-socket door, and with trustProxy on (server/src/app.ts) a directly reachable
  # panel believes whatever X-Forwarded-For it is handed, which walks around the per-IP login limit.
  if [ "$PROXY_ENABLE" = "yes" ]; then
    if [ -n "${PUBLIC_BIND:-}" ]; then
      PROXY_BIND="$PUBLIC_BIND"
    elif [ "$BIND_SET" = "yes" ]; then
      PROXY_BIND="$PANEL_BIND"
    fi
    PANEL_BIND="127.0.0.1"
  elif [ -n "${PUBLIC_BIND:-}" ]; then
    PANEL_BIND="$PUBLIC_BIND"
  fi

  # NODE_ENV and COOKIE_SECURE move together, and the pairing is not a preference. The config layer
  # refuses to boot a production panel with an insecure session cookie (resolveCookieSecure in
  # server/src/config.ts). With TLS the cookie is secure and production is correct. Without TLS a
  # secure cookie is one a browser will not send over http, so sign-in fails in a browser while curl
  # keeps working: that was the bug here, and development is the mode that permits the insecure
  # cookie. It changes nothing else in the server, because config.env is read only by that cookie
  # decision and by the two places that report it.
  if [ "$TLS_ON" = "yes" ]; then
    NODE_ENV_VALUE="production"
    COOKIE_SECURE_VALUE="true"
  else
    NODE_ENV_VALUE="development"
    COOKIE_SECURE_VALUE="false"
  fi

  # PUBLIC_URL is what the panel calls itself in the links it shows, so it has to be the address a
  # person actually types.
  if [ -z "$PUBLIC_URL" ] && [ "$PROXY_ENABLE" = "yes" ]; then
    PROXY_HOST="${DOMAIN:-$(detect_host_ip)}"
    if [ "$TLS_ON" = "yes" ]; then
      PUBLIC_URL="https://$PROXY_HOST"
      [ "$PROXY_HTTPS_PORT" = "443" ] || PUBLIC_URL="$PUBLIC_URL:$PROXY_HTTPS_PORT"
    else
      PUBLIC_URL="http://$PROXY_HOST"
      [ "$PROXY_HTTP_PORT" = "80" ] || PUBLIC_URL="$PUBLIC_URL:$PROXY_HTTP_PORT"
    fi
  fi

  # The compose file gates the nginx service behind the "proxy" profile. Setting COMPOSE_PROFILES in
  # .env rather than passing --profile on every command is deliberate: deploy/update.sh, a manual
  # `docker compose up -d` and the installer's own calls then all agree, and an update cannot
  # silently drop the proxy and republish the panel.
  if [ "$PROXY_ENABLE" = "yes" ]; then
    COMPOSE_PROFILES_VALUE="proxy"
  else
    COMPOSE_PROFILES_VALUE=""
  fi
}

# Runs the setup unless it was switched off, the flags already answered the questions, or there is no
