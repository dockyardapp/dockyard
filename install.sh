if [ "$TOUCH_FIREWALL" = "yes" ]; then
  # Which ports have to be reachable from outside. With the proxy in front the panel is on loopback
  # and nginx is the only door, so opening PANEL_PORT would open nothing useful, and leaving the
  # proxy's ports closed would make the panel unreachable.
  FIREWALL_PORTS=""
  if [ "$PROXY_ENABLE" = "yes" ]; then
    [ "$PROXY_BIND" != "127.0.0.1" ] && FIREWALL_PORTS="$PROXY_HTTP_PORT $PROXY_HTTPS_PORT"
  elif [ "$PANEL_BIND" != "127.0.0.1" ]; then
    FIREWALL_PORTS="$PANEL_PORT"
  fi

  if [ -n "$FIREWALL_PORTS" ] && command -v ufw >/dev/null 2>&1 && ufw status 2>/dev/null | grep -q '^Status: active'; then
    step "Firewall"
    for port in $FIREWALL_PORTS; do
      if ufw status | grep -qE "^$port(/tcp)?\b.*ALLOW"; then
        say "ufw already allows $port"
      else
        run ufw allow "$port/tcp"
        say "ufw: allowed $port/tcp, or nothing outside the host could reach the panel"
      fi
    done
  elif [ -n "$FIREWALL_PORTS" ] && command -v firewall-cmd >/dev/null 2>&1 && firewall-cmd --state >/dev/null 2>&1; then
    step "Firewall"
    for port in $FIREWALL_PORTS; do
      run firewall-cmd --permanent --add-port="$port/tcp"
    done
    run firewall-cmd --reload
    say "firewalld: allowed $FIREWALL_PORTS/tcp"
  fi
fi

