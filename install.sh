  fi
  [ -f "$template" ] || die "the checkout has no $template, so the proxy cannot be configured."

  out="$NGINX_DIR/dockyard.conf"
  sed -e "s|@@SERVER_NAME@@|$NGINX_SERVER_NAME|g" \
      -e "s|@@UPSTREAM@@|$NGINX_UPSTREAM|g" \
      -e "s|@@CERT_FILE@@|$NGINX_CERT_FILE|g" \
      -e "s|@@KEY_FILE@@|$NGINX_KEY_FILE|g" \
      "$template" > "$out.tmp"

  if grep -q '@@[A-Z_]*@@' "$out.tmp"; then
    rm -f "$out.tmp"
    die "a placeholder was left unsubstituted in $(basename "$template"). This is a bug in the installer."
  fi

  # OCSP stapling needs an issuer to ask, and a self-signed certificate has none, so nginx logs
  # `"ssl_stapling" ignored, issuer certificate not found` on every start. It is only a warning, but
  # it is the kind that sends someone looking for a problem that is not there, and the directive
  # cannot do anything useful here.
  if [ "$CERT_MODE" = "self-signed" ]; then
    sed -i 's|^\([[:space:]]*\)\(ssl_stapling[^;]*;\)|\1# \2  # self-signed: no issuer to staple|' "$out.tmp"
  fi

  mv "$out.tmp" "$out"
  say "rendered $(basename "$out") ($which)"
}

# Everything the proxy needs before anything starts. The rendered config has to exist first: it is a
# bind-mount source, and Docker turns a missing bind-mount source into an empty directory, which nginx
# then fails to read as a config.
setup_proxy() {
  [ "$PROXY_ENABLE" = "yes" ] || return 0
  if [ "$DRY_RUN" = "yes" ]; then
    say "[dry-run] would render data/nginx/dockyard.conf and set up a $CERT_MODE certificate"
    return 0
  fi

  step "Setting up nginx"

  run mkdir -p "$NGINX_CERTS" "$NGINX_WWW"
  # nginx serves the ACME challenge from this directory, and certbot writes into it as its own uid, so
  # it cannot be 0700.
  chmod 0755 "$NGINX_WWW"
  # The private key is written 0600 by gen-cert.sh. nginx runs as its own user inside the container and
  # reads the mounted file as root at startup, so the key stays unreadable to anything else on the host.
  chmod 0755 "$NGINX_CERTS"

  NGINX_SERVER_NAME="${DOMAIN:-_}"

  if [ "$TLS_ON" != "yes" ]; then
    render_nginx_config http
    return 0
  fi

  if [ "$CERT_MODE" = "letsencrypt" ]; then
    # The challenge needs this host answering on port 80, which means nginx has to be up first. Start
    # on the HTTP config, then swap in the TLS one once the certificate exists.
    LE_PENDING="yes"
    render_nginx_config http
    say "starting on HTTP so Let's Encrypt can reach the challenge, then switching to TLS"
    return 0
  fi

  GEN="$INSTALL_DIR/deploy/nginx/gen-cert.sh"
  if [ ! -x "$GEN" ]; then
    die "$GEN is missing or not executable, so no certificate can be made. The checkout is incomplete."
  fi

  # gen-cert.sh is idempotent, so a re-run keeps a certificate the browser already trusts, and prints
  # the paths it wrote for the config to use.
  GEN_OUT="$(run "$GEN" "$DOMAIN" "$NGINX_CERTS")" || die "generating a certificate for $DOMAIN failed. The output above says why."
  printf '%s\n' "$GEN_OUT" | head -1 | while IFS= read -r line; do say "$line"; done
  NGINX_CERT_FILE="$(printf '%s\n' "$GEN_OUT" | sed -n 's/^CERT_FILE=//p' | head -1)"
  NGINX_KEY_FILE="$(printf '%s\n' "$GEN_OUT" | sed -n 's/^KEY_FILE=//p' | head -1)"
  if [ -z "$NGINX_CERT_FILE" ] || [ -z "$NGINX_KEY_FILE" ]; then
    die "gen-cert.sh did not report the paths it wrote, so the nginx config cannot be rendered."
  fi

  render_nginx_config tls
}

# Let's Encrypt can only be issued once this host answers on port 80, so it runs after the stack is
# up. certbot is a one-off container rather than a service: it has nothing to do between runs, and a
# restart policy on something that exits would only produce a crash loop.
#
# The layout it writes (certs/live/<name>/fullchain.pem) is certbot's own, and it is the same tree
# nginx already mounts, so a renewal is `certbot renew` plus a reload and nothing here changes.
setup_letsencrypt() {
  [ "$LE_PENDING" = "yes" ] || return 0

  step "Getting a Let's Encrypt certificate for $DOMAIN"

  if ! run docker run --rm \
      -v "$NGINX_CERTS:/etc/letsencrypt" \
      -v "$NGINX_WWW:/var/www/certbot" \
      certbot/certbot certonly --webroot -w /var/www/certbot \
        -d "$DOMAIN" --email "$ADMIN_EMAIL" --agree-tos --no-eff-email \
        --non-interactive --keep-until-expiring; then
    warn "Let's Encrypt could not confirm that $DOMAIN points here."
    warn "That needs the domain to resolve to this host's public address and port 80 to be reachable"
    warn "from the internet. The panel is running on plain HTTP meanwhile, so it is reachable and"
    warn "sign-in works. Re-run with the DNS fixed and the same --proxy --cert letsencrypt --domain,"
    warn "or drop to --cert self-signed to use a certificate that needs no validation."
    die "no certificate was issued, so nginx was left on the plain HTTP config rather than being"
  fi

  NGINX_CERT_FILE="live/$DOMAIN/fullchain.pem"
  NGINX_KEY_FILE="live/$DOMAIN/privkey.pem"
  render_nginx_config tls

  # The config file is bind-mounted read-only, so nginx has to be told to re-read it.
  if ! run "${COMPOSE[@]}" exec -T nginx nginx -s reload; then
    die "nginx would not reload the TLS config. 'cd $INSTALL_DIR && ${COMPOSE[*]} logs nginx' says why."
  fi
  say "nginx is serving TLS for $DOMAIN"
}

